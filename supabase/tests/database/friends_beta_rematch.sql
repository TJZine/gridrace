create function pg_temp.exercise(p_count smallint) returns setof text language plpgsql as $$
declare a uuid:='f3000000-0000-0000-0000-000000000001'; b uuid:='f3000000-0000-0000-0000-000000000002';
 outsider uuid:='f3000000-0000-0000-0000-000000000003'; m uuid; s uuid; r uuid; n integer; req uuid:=extensions.gen_random_uuid();
 accept_req uuid:=extensions.gen_random_uuid(); offer jsonb; accepted jsonb; snap jsonb; original jsonb; epoch_a bigint; epoch_b bigint; v_revision bigint; active_words text[];
begin
 delete from private.user_rate_limits;
 m:=(public.create_match(a,3,null,extensions.gen_random_uuid(),p_count)#>>'{data,match_id}')::uuid;
 perform public.join_match(b,3,(select join_code from public.matches where id=m),null,extensions.gen_random_uuid(),null);
 for n in 1..p_count loop
   perform public.start_match(a,3,m,n::smallint);
   select id into r from public.rounds where match_id=m and round_number=n;
   update public.rounds set starts_at=now()-interval '4 minutes',ends_at=now()-interval '1 minute' where id=r;
   perform private.finalize_round(r);
 end loop;
 select to_jsonb(x) into original from public.matches x where id=m;
 select revision into v_revision from public.matches where id=m;
 snap:=public.match_snapshot(a,3,m)->'data';
 return next is(snap->>'version','3',p_count||': v3');
 return next is(snap#>>'{rematch,state}','eligible',p_count||': eligible');
 return next is(public.match_snapshot(a,3,m)#>>'{data,selection,epoch}',snap#>>'{selection,epoch}',p_count||': passive read does not select');
 epoch_a:=(snap#>>'{selection,epoch}')::bigint;
 offer:=public.rematch_command(a,3,req,m,1,'offer',epoch_a);
 return next is(offer#>>'{data,state}','offered',p_count||': first consent');
 return next is(public.rematch_command(a,3,req,m,1,'offer',epoch_a),offer,p_count||': exact offer replay');
 return next is(public.rematch_command(a,3,req,m,1,'cancel',epoch_a)#>>'{error,code}','request_conflict',p_count||': changed payload conflicts');
 return next is(public.rematch_command(outsider,3,extensions.gen_random_uuid(),m,1,'accept',0)#>>'{error,code}','not_a_match_member',p_count||': outsider denied');
 epoch_b:=(public.match_snapshot(b,3,m)#>>'{data,selection,epoch}')::bigint;
 accepted:=public.rematch_command(b,3,accept_req,m,1,'accept',epoch_b);
 s:=(accepted#>>'{data,successor_match_id}')::uuid;
 return next ok(s is not null,p_count||': successor allocated');
 return next is(public.rematch_command(b,3,accept_req,m,1,'accept',epoch_b),accepted,p_count||': exact acceptance replay');
 return next is((select to_jsonb(x) from public.matches x where id=m),original,p_count||': predecessor completely immutable');
 return next is((select count(*) from public.match_members where match_id=s),2::bigint,p_count||': exactly two fresh members');
 return next ok(not exists(select 1 from public.match_members x join public.match_members y on x.id=y.id where x.match_id=m and y.match_id=s),p_count||': no reused member ID');
 return next is((select round_count from public.matches where id=s),p_count,p_count||': same count');
 return next is((select auth_user_id from public.match_members where id=(select creator_member_id from public.matches where id=s)),a,p_count||': original creator');
 return next is((select expires_at-created_at from public.matches where id=s),interval '60 minutes',p_count||': full lobby lifetime');
 return next is(public.match_snapshot(a,3,m)#>>'{data,selection,is_selected}','false',p_count||': predecessor unselected');
 return next is(public.match_snapshot(a,3,m)#>>'{data,rematch,selected_elsewhere}','false',p_count||': successor is not elsewhere');
 return next is(public.match_snapshot(a,3,s)#>>'{data,match,admission}','rematch',p_count||': private admission');
 return next is(public.join_match(outsider,3,(select join_code from public.matches where id=s),null,extensions.gen_random_uuid(),null)#>>'{error,code}','match_not_joinable',p_count||': outsider cannot join successor');
 return next is((select cardinality(excluded_answers) from private.rematch_successors where match_id=s),p_count::integer,p_count||': all exclusions copied');
 return next is((select count(*) from private.round_secrets x join public.rounds y on y.id=x.round_id where y.match_id=s),0::bigint,p_count||': no future answer selection');
 for n in 1..p_count loop
   return next ok(public.start_match(a,3,s,n::smallint)?'data',p_count||': successor start '||n);
   select id into r from public.rounds where match_id=s and round_number=n;
   return next ok(not exists(select 1 from private.round_secrets x join private.rematch_successors y on x.answer=any(y.excluded_answers) where x.round_id=r and y.match_id=s),p_count||': excludes predecessor '||n);
   update public.rounds set starts_at=now()-interval '4 minutes',ends_at=now()-interval '1 minute' where id=r;
   perform private.finalize_round(r);
   if n=1 and p_count>1 then
     select array_agg(word) into active_words from private.words where is_active;
     update private.words set is_active=false where is_answer;
     return next is(public.start_match(a,3,s,2::smallint)#>>'{error,code}','answer_pool_unavailable',p_count||': later start pool failure');
     return next is((select current_round from public.matches where id=s),1::smallint,p_count||': later pool failure no advance');
     return next is((select count(*) from private.round_secrets x join public.rounds y on y.id=x.round_id where y.match_id=s),1::bigint,p_count||': later pool failure no secret');
     update private.words set is_active=true where word=any(active_words);
   end if;
 end loop;
 return next is((select count(distinct x.answer) from private.round_secrets x join public.rounds y on y.id=x.round_id where y.match_id=s),p_count::bigint,p_count||': no successor repeat');
 return next is(public.match_snapshot(a,3,s)#>>'{data,rematch,state}','eligible',p_count||': successor can rematch');
end $$;
create function pg_temp.snapshot_clock_boundaries() returns setof text language plpgsql as $$
declare a uuid:='f3000000-0000-0000-0000-000000000001'; b uuid:='f3000000-0000-0000-0000-000000000002';
 m uuid; r uuid; boundary timestamptz; snap jsonb;
begin
 delete from private.user_rate_limits;
 m:=(public.create_match(a,3,null,extensions.gen_random_uuid(),1::smallint)#>>'{data,match_id}')::uuid;
 perform public.join_match(b,3,(select join_code from public.matches where id=m),null,extensions.gen_random_uuid(),null);
 perform public.start_match(a,3,m,1::smallint);
 select id into r from public.rounds where match_id=m;
 -- Cross a deadline inside this transaction without a three-minute fixture wait.
 boundary:=transaction_timestamp()+interval '1 millisecond';
 perform pg_sleep(0.002);
 return next ok(transaction_timestamp()<boundary and clock_timestamp()>boundary,'clock fixture straddles transaction and wall time');
 update public.matches set started_at=boundary-interval '3 seconds' where id=m;
 update public.rounds set starts_at=boundary,ends_at=boundary+interval '180 seconds' where id=r;
 update public.player_rounds set started_at=boundary where round_id=r;
 snap:=public.match_snapshot(a,3,m);
 return next is(snap#>>'{data,round,state}','countdown','countdown uses its snapshot evaluation time');
 return next ok((snap#>>'{data,server_time}')::timestamptz<(snap#>>'{data,round,starts_at}')::timestamptz,
   'countdown timestamp remains before start after wall clock crosses start');
 update public.matches set started_at=boundary-interval '183 seconds' where id=m;
 update public.rounds set starts_at=boundary-interval '180 seconds',ends_at=boundary where id=r;
 update public.player_rounds set started_at=boundary-interval '180 seconds' where round_id=r;
 snap:=public.match_snapshot(a,3,m);
 return next is(snap#>>'{data,round,state}','playing','playing uses its snapshot evaluation time');
 return next ok((snap#>>'{data,server_time}')::timestamptz>=(snap#>>'{data,round,starts_at}')::timestamptz
   and (snap#>>'{data,server_time}')::timestamptz<(snap#>>'{data,round,ends_at}')::timestamptz,
   'playing timestamp remains inside round after wall clock crosses end');
 update public.rounds set starts_at=boundary-interval '8 minutes',ends_at=boundary-interval '5 minutes' where id=r;
 return next ok(private.finalize_round(r),'completed clock fixture finalizes');
 update public.matches set started_at=boundary-interval '8 minutes 3 seconds',completed_at=boundary-interval '5 minutes' where id=m;
 update public.rounds set completed_at=boundary-interval '5 minutes' where id=r;
 update public.player_rounds set started_at=boundary-interval '8 minutes',finished_at=boundary-interval '5 minutes' where round_id=r;
 snap:=public.match_snapshot(a,3,m);
 return next is(snap#>>'{data,rematch,state}','expired','completed rematch uses wall deadline even when transaction time precedes it');
 return next ok((snap#>>'{data,rematch,evaluated_at}')::timestamptz>=(snap#>>'{data,rematch,deadline}')::timestamptz,
   'rematch expiration is evaluated at or after its original deadline');
 return next ok((snap#>>'{data,rematch,evaluated_at}')::timestamptz<=(snap#>>'{data,server_time}')::timestamptz,
   'completed snapshot covers its rematch evaluation time');
end $$;
